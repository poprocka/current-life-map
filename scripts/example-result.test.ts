// Generates docs/example-result.json from a realistic sample respondent (run: npx vitest run scripts/example-result.test.ts)
import { it } from "vitest";
import fs from "fs";
import { computeLifeMap } from "@/engine/compute";
import { ACTIVE_QUESTIONS } from "@/content/v10/question-bank";
import { NOT_APPLICABLE } from "@/content/types";

it("writes example", () => {
  const a: Record<string, string | string[]> = {}; let i = 0;
  const truth = ["3", "2", "4", "1", "3", "2", "3"];
  const imp: Record<string, string> = { mind: "3", body: "4", restoration: "4", growth: "3", love: "1", social: "4", resources: "2", joy: "2" };
  const en: Record<string, string> = { mind: "-1", body: "0", restoration: "-2", growth: "1", love: "0", social: "-1", resources: "0", joy: "2" };
  const feel: Record<string, number[]> = { mind: [0, 8], body: [1, 2], restoration: [10, 11, 7], growth: [4, 11], love: [5], social: [9, 10], resources: [0, 6], joy: [0, 4] };
  for (const q of ACTIVE_QUESTIONS) {
    if (q.responseType === "importance") a[q.id] = imp[q.chapterId];
    else if (q.responseType === "energy") a[q.id] = en[q.chapterId];
    else if (q.responseType === "truth") a[q.id] = q.chapterId === "restoration" ? "1" : truth[i++ % 7];
    else if (q.responseType === "emotional_state") a[q.id] = feel[q.chapterId].map((k) => q.options[k].value);
  }
  Object.assign(a, { "love.02": NOT_APPLICABLE, "interconnections.01": "social", "interconnections.02": "joy", "interconnections.03": "restoration",
    "interconnections.04": "restoration", "interconnections.05": "growth", "interconnections.06": "resources", "interconnections.07": "somewhat_compete" });
  const r = computeLifeMap(a);
  fs.writeFileSync("docs/example-result.json", JSON.stringify({ _note: "Illustrative sample respondent, not real data. Generated by scripts/example-result.test.ts.", ...r }, null, 2));
});
