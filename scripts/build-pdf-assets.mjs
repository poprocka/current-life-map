// Builds the emailed PDF's assets. 1) The stylesheet: the app's Tailwind CSS (same tokens as the page), the two brand fonts
// embedded (so the PDF never depends on a network fetch), and print rules. Output is committed and regenerated on build.
import { execFileSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");
const tmp = path.join(root, "node_modules/.cache/print.css");
fs.mkdirSync(path.dirname(tmp), { recursive: true });
execFileSync("npx", ["tailwindcss", "-i", "src/app/globals.css", "-c", "tailwind.config.ts", "--content", "./src/**/*.tsx", "-o", tmp, "--minify"], { cwd: root, stdio: ["ignore", "ignore", "inherit"] });
const app = fs.readFileSync(tmp, "utf8");

const font = (pkg, file, family, weight, style) => {
  const b64 = fs.readFileSync(path.join(root, "node_modules/@fontsource", pkg, "files", file)).toString("base64");
  return `@font-face{font-family:${family};font-style:${style};font-weight:${weight};font-display:block;src:url(data:font/woff2;base64,${b64}) format("woff2")}`;
};
const fonts = [
  ...[300, 400, 500].flatMap((w) => ["normal", "italic"].map((st) => font("cormorant-garamond", `cormorant-garamond-latin-${w}-${st}.woff2`, '"Cormorant Garamond"', w, st))),
  ...[300, 400, 500].map((w) => font("poppins", `poppins-latin-${w}-normal.woff2`, "Poppins", w, "normal")),
].join("");

const print = `
@page{size:A4;margin:12mm 0 16mm}
html,body{background:#F5EDE2;-webkit-print-color-adjust:exact;print-color-adjust:exact}
.pdf-keep{break-inside:avoid;page-break-inside:avoid}
.pdf-break-before{break-before:page;page-break-before:always}
section,article,li{orphans:3;widows:3}
h1,h2,h3,.pdf-with-next{break-after:avoid;page-break-after:avoid}
a{text-decoration-skip-ink:auto}
`;

const out = `// GENERATED by scripts/build-pdf-assets.mjs — do not edit. Regenerate with: node scripts/build-print-css.mjs
export const PRINT_CSS: string = ${JSON.stringify(fonts + app + print)};
`;
fs.writeFileSync(path.join(root, "src/server/pdf/print-assets.generated.ts"), out);
console.log(`print css: ${(out.length / 1024).toFixed(0)} KB`);

// The HTML renderer, bundled (CommonJS) with its own React so it runs as plain server code (no client-component boundaries).
const esbuild = await import("esbuild");
await esbuild.build({
  entryPoints: [path.join(root, "src/server/pdf/html.tsx")],
  outfile: path.join(root, "src/server/pdf/document.generated.cjs"),
  bundle: true, platform: "node", format: "cjs", target: "node18", jsx: "automatic", minify: true, legalComments: "none",
  alias: { "@": path.join(root, "src") },
  define: { "process.env.NODE_ENV": '"production"' },
  banner: { js: "// GENERATED by scripts/build-pdf-assets.mjs — do not edit.\n// @ts-nocheck" },
  logLevel: "error",
});
console.log(`pdf html renderer: ${(fs.statSync(path.join(root, "src/server/pdf/document.generated.cjs")).size / 1024).toFixed(0)} KB`);
